# src/train.py
# Purpose: Train the final model, set its decision threshold, evaluate it once
#          on the held-out test set, and save the model with its metadata.
#
# The final model and recall target are chosen in src/config.py from the
# cross-validation report (python -m src.cross_validate). Nothing in this
# script feeds test-set results back into those choices.

import json
import platform

import joblib
import numpy as np
import pandas as pd
import sklearn
from sklearn.metrics import average_precision_score, brier_score_loss, roc_auc_score

from .config import (
    BASELINE_MODEL,
    FINAL_MODEL,
    METADATA_PATH,
    MODEL_PATH,
    PROJECT_ROOT,
    RECALL_TARGET,
)
from .cross_validate import run_cv
from .evaluate import TEST_METRICS, evaluate_on_test, paired_bootstrap_difference
from .models import load_split, build_model
from .plots import save_confusion_matrix, save_feature_importance, save_roc_curve
from .threshold import threshold_table

REPORTS_DIR = PROJECT_ROOT / "reports"
FIGURES_DIR = REPORTS_DIR / "figures"

METRIC_LABELS = {
    "roc_auc": "ROC-AUC",
    "pr_auc": "PR-AUC",
    "brier": "Brier score",
    "recall": "Recall",
    "precision": "Precision",
    "specificity": "Specificity",
    "f1": "F1",
}


def choose_threshold(X_train, y_train):
    """
    Threshold from out-of-fold predictions on the training split only:
    in each CV repeat, the highest threshold that reaches the recall target;
    the median across repeats is used.
    """

    _, oof = run_cv(X_train, y_train, candidates=[FINAL_MODEL])
    row = threshold_table(y_train, oof[FINAL_MODEL], [RECALL_TARGET]).iloc[0]

    return float(row["threshold"]), {
        "recall": float(row["recall_mean"]),
        "precision": float(row["precision_mean"]),
        "specificity": float(row["specificity_mean"]),
        "flagged_share": float(row["flagged_share_mean"]),
    }


def baseline_on_test(X_train, y_train, X_test, y_test, proba):
    """
    Score the age-only baseline on the same test patients, for comparison.

    This was added after the final model's test results had been seen, so it
    checks the final model; it does not feed back into any choice.
    """

    baseline = build_model(BASELINE_MODEL).fit(X_train, y_train)
    baseline_proba = baseline.predict_proba(X_test)[:, 1]

    return {
        "roc_auc": float(roc_auc_score(y_test, baseline_proba)),
        "pr_auc": float(average_precision_score(y_test, baseline_proba)),
        "brier": float(brier_score_loss(y_test, baseline_proba)),
        "roc_auc_difference": paired_bootstrap_difference(y_test, proba, baseline_proba),
    }


def write_test_report(test, cv_at_threshold, top_features, baseline):

    m, ci = test["metrics"], test["ci95"]
    c = test["confusion"]

    lines = [
        "# Final model: test-set evaluation",
        "",
        "Generated by `python run.py`.",
        "",
        f"* Model: `{FINAL_MODEL}` (random forest, sigmoid-calibrated), trained on the full training split",
        f"* Decision threshold: **{test['threshold']:.3f}**, chosen on the training split from "
        f"out-of-fold predictions to reach a recall of {RECALL_TARGET:.2f}",
        f"* Test set: {test['n_patients']} patients ({test['n_icu']} admitted to ICU), held out "
        "from every earlier step and used once, after the model and threshold were fixed",
        "",
        "## Results",
        "",
        f"95% intervals from {test['n_bootstrap']} bootstrap resamples of the test patients.",
        "",
        "| Metric | Test set | 95% interval | Cross-validation (training split) |",
        "| --- | --- | --- | --- |",
    ]

    for metric in TEST_METRICS:
        cv_value = cv_at_threshold.get(metric)
        cv_cell = f"{cv_value:.3f}" if cv_value is not None else "see cv_report.md"
        lines.append(
            f"| {METRIC_LABELS[metric]} | {m[metric]:.3f} "
            f"| {ci[metric]['low']:.3f} – {ci[metric]['high']:.3f} | {cv_cell} |"
        )

    lines += [
        "",
        "Recall, precision, specificity and F1 are at the decision threshold. "
        "Cross-validation values at the threshold are means over the 10 CV repeats.",
        "",
        "## Confusion matrix at the threshold",
        "",
        "| | Predicted ICU | Predicted no ICU |",
        "| --- | --- | --- |",
        f"| **Admitted to ICU** | {c['tp']} | {c['fn']} |",
        f"| **Not admitted** | {c['fp']} | {c['tn']} |",
        "",
        f"The model flags {m['flagged_share']:.0%} of test patients for ICU review.",
        "",
        "## Compared with an age-only baseline",
        "",
        f"The same test patients scored by `{BASELINE_MODEL}`: logistic regression on the age group "
        "alone, trained on the same training split. This comparison was added after the final "
        "model's test results had been seen, so it is a check on the final model, not a model choice; "
        "the final model was not changed.",
        "",
        f"| Metric | Final model | {BASELINE_MODEL} |",
        "| --- | --- | --- |",
        f"| ROC-AUC | {m['roc_auc']:.3f} | {baseline['roc_auc']:.3f} |",
        f"| PR-AUC | {m['pr_auc']:.3f} | {baseline['pr_auc']:.3f} |",
        f"| Brier score | {m['brier']:.3f} | {baseline['brier']:.3f} |",
        "",
        f"ROC-AUC difference (final model minus baseline): "
        f"{baseline['roc_auc_difference']['difference']:+.3f}, 95% interval "
        f"{baseline['roc_auc_difference']['low']:+.3f} to {baseline['roc_auc_difference']['high']:+.3f} "
        f"(paired bootstrap, {test['n_bootstrap']} resamples of the test patients).",
        "",
        "## Most important features",
        "",
        "Impurity-based importances from the random forests inside the calibrated model, averaged, "
        "summed per measurement (one-hot columns and the identical MEAN/MEDIAN/MIN/MAX copies of each lab combined). "
        "They show what the model relies on, not causal effects.",
        "",
    ]

    for name, value in top_features.head(10).items():
        lines.append(f"* `{name}`: {value:.3f}")

    lines += [
        "",
        "Figures: `reports/figures/roc_test.png`, `reports/figures/cm_test.png`, "
        "`reports/figures/fi_top20.png`.",
    ]

    (REPORTS_DIR / "evaluation_test.md").write_text("\n".join(lines) + "\n")


def train_final():

    if FINAL_MODEL is None or RECALL_TARGET is None:
        raise RuntimeError("Set FINAL_MODEL and RECALL_TARGET in src/config.py first")

    X_train, X_test, y_train, y_test = load_split()

    # 1. Decision threshold, from the training split only
    threshold, cv_at_threshold = choose_threshold(X_train, y_train)

    # 2. Final model, fitted on the whole training split
    model = build_model(FINAL_MODEL).fit(X_train, y_train)

    # 3. One evaluation on the held-out test set
    proba = model.predict_proba(X_test)[:, 1]
    test = evaluate_on_test(y_test, proba, threshold)

    # 4. Save the model and everything the API needs to use it
    MODEL_PATH.parent.mkdir(parents=True, exist_ok=True)
    joblib.dump(model, MODEL_PATH, compress=3)

    cv_summary_path = PROJECT_ROOT / "results" / "cv_summary.json"
    cv_summary = json.loads(cv_summary_path.read_text()) if cv_summary_path.exists() else {}

    metadata = {
        "model": FINAL_MODEL,
        "model_file": MODEL_PATH.name,
        "threshold": threshold,
        "recall_target": RECALL_TARGET,
        "threshold_method": (
            "Median over 10 cross-validation repeats of the highest threshold whose "
            "out-of-fold recall on the training split reaches the recall target"
        ),
        "feature_columns": list(X_train.columns),
        "training_split": {"n_patients": int(len(y_train)), "n_icu": int(y_train.sum())},
        "cross_validation": {
            "summary": cv_summary.get("summary", {}).get(FINAL_MODEL),
            "calibration": cv_summary.get("calibration", {}).get(FINAL_MODEL),
            "at_threshold": cv_at_threshold,
        },
        "test": test,
        "versions": {
            "python": platform.python_version(),
            "scikit-learn": sklearn.__version__,
            "pandas": pd.__version__,
            "numpy": np.__version__,
            "joblib": joblib.__version__,
        },
    }

    METADATA_PATH.write_text(json.dumps(metadata, indent=2) + "\n")

    # 5. Report and figures
    FIGURES_DIR.mkdir(parents=True, exist_ok=True)
    save_roc_curve(y_test, proba, FIGURES_DIR / "roc_test.png", title="ROC curve, test set")
    save_confusion_matrix(y_test, (proba >= threshold).astype(int), FIGURES_DIR / "cm_test.png", threshold)
    top_features = save_feature_importance(model, FIGURES_DIR / "fi_top20.png")
    baseline = baseline_on_test(X_train, y_train, X_test, y_test, proba)
    write_test_report(test, cv_at_threshold, top_features, baseline)

    return model, metadata
